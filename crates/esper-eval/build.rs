//! Compile-time discovery of the golden fixtures.
//!
//! This build script reads `spec/trajectories/` and generates one
//! `#[test]` per `*.json` file into `$OUT_DIR/fixture_tests.rs`, which
//! `tests/fixtures.rs` includes. Adding a ninth fixture file therefore
//! adds a ninth test with no code change: the directory is the test
//! list. Each generated test calls
//! `esper_eval::runner::run_fixture_file` with the fixture's path and
//! panics with the full [`esper_eval::FixtureError`] report on failure.
//!
//! `cargo:rerun-if-changed` is emitted for every fixture file, so
//! adding, removing, or editing a fixture re-runs the script.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// Turn a fixture file name into a test function name.
///
/// `a-success-read-write-verify-finish.json` becomes
/// `trajectory_a_success_read_write_verify_finish`. Any character that
/// is not alphanumeric becomes an underscore, so an unexpected file
/// name can never produce invalid Rust.
fn test_name(file_name: &str) -> String {
    // HOST-ONLY (E0/E1)
    let stem = file_name
        .strip_suffix(".json")
        .map_or(file_name, |stem| stem);
    let mut name = String::from("trajectory_");
    for ch in stem.chars() {
        if ch.is_ascii_alphanumeric() {
            name.push(ch);
        } else {
            name.push('_');
        }
    }
    name
}

/// A build-script failure: print the message and fail the build.
fn fail(message: &str) -> Result<(), Box<dyn std::error::Error>> {
    Err(message.into())
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let dir = manifest.join("../../spec/trajectories");
    println!("cargo:rerun-if-changed={}", dir.display());

    // HOST-ONLY (E0/E1)
    let mut names: Vec<String> = Vec::new();
    for entry in fs::read_dir(&dir)? {
        let entry = entry?;
        let path = entry.path();
        let name = entry
            .file_name()
            .into_string()
            .map_err(|_| "a fixture file name is not UTF-8")?;
        if Path::new(&name)
            .extension()
            .is_some_and(|ext| ext.eq_ignore_ascii_case("json"))
        {
            println!("cargo:rerun-if-changed={}", path.display());
            names.push(name);
        }
    }
    names.sort();
    if names.is_empty() {
        return fail("no golden fixtures found in spec/trajectories");
    }

    // HOST-ONLY (E0/E1)
    let mut code = String::new();
    code.push_str(
        "// Generated by build.rs: one test per golden fixture file.\n\
         // Do not edit; the fixture directory is the source of truth.\n\n",
    );
    for name in &names {
        let fn_name = test_name(name);
        code.push_str("#[test]\n");
        let _ = writeln!(code, "fn {fn_name}() {{");
        code.push_str("    if let Err(err) = esper_eval::runner::run_fixture_file(concat!(\n");
        code.push_str("        env!(\"CARGO_MANIFEST_DIR\"),\n");
        let _ = writeln!(code, "        \"/../../spec/trajectories/{name}\"");
        code.push_str("    )) {\n");
        let _ = writeln!(
            code,
            "        panic!(\"golden fixture {name} failed:\\n{{err}}\");"
        );
        code.push_str("    }\n");
        code.push_str("}\n\n");
    }

    let out = PathBuf::from(env::var("OUT_DIR")?).join("fixture_tests.rs");
    fs::write(out, code)?;
    Ok(())
}
